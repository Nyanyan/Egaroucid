"""NNUE pattern set: one definition shared by the trainer and the engine header.

Cells are (x, y) with x = column a..h -> 0..7, y = row 1..8 -> 0..7.
Bitboards follow Egaroucid: bit 63 - (8 * y + x), so a1 is bit 63 and h8 is bit 0.

Each base pattern's cells are ordered by ascending bit index. An instance is the image of the base
pattern under one of the 8 board symmetries s; its k-th digit is the cell s(base cell k). Instances
whose cell sets coincide are dropped (the first symmetry in SYMMETRIES order is kept). The engine
computes an instance index as pext(T_{s^-1}(board), base mask), which yields exactly this digit order.

Digit of a cell: 0 = empty, 1 = side to move, 2 = opponent. Index = sum(digit_k * 3^k).

Usage: python src/tools/nnue/nnue_patterns.py --header src/engine/nnue/nnue_patterns.hpp
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def cell(name):
    return (ord(name[0]) - ord("a"), int(name[1]) - 1)


def cells(*names):
    return [cell(n) for n in names]


def row(y):
    return [(x, y) for x in range(8)]


# The 12 shapes from the user's reference engine (2026-10-19), all 9 cells or fewer.
BASE_PATTERNS = [
    ("row1", row(0)),
    ("row2", row(1)),
    ("row3", row(2)),
    ("row4", row(3)),
    ("zigzag_c1", cells("a3", "b2", "c1", "d2", "e3", "f4", "g5", "h6")),
    ("zigzag_d1", cells("a4", "b3", "c2", "d1", "e2", "f3", "g4", "h5")),
    ("diag7_2corner", cells("a1", "b1", "c2", "d3", "e4", "f5", "g6", "h7", "h8")),
    ("diag8_g2", cells("a1", "b2", "c3", "d4", "e5", "f6", "g7", "h8", "g2")),
    ("corner3x3", cells("a1", "b1", "c1", "a2", "b2", "c2", "a3", "b3", "c3")),
    ("corner_l", cells("a1", "b1", "c1", "d1", "e1", "a2", "a3", "a4", "a5")),
    ("block2x4_h1", cells("a1", "b1", "c1", "d1", "a2", "b2", "c2", "d2", "h1")),
    ("edge7_b2c2", cells("a1", "b1", "c1", "d1", "e1", "f1", "g1", "b2", "c2")),
]

# (x, y) -> image under each symmetry
SYMMETRIES = [
    lambda x, y: (x, y),          # 0 identity
    lambda x, y: (7 - x, y),      # 1 mirror columns
    lambda x, y: (x, 7 - y),      # 2 mirror rows
    lambda x, y: (7 - x, 7 - y),  # 3 rotate 180
    lambda x, y: (y, x),          # 4 transpose (a1-h8 diagonal)
    lambda x, y: (7 - y, 7 - x),  # 5 anti-transpose (h1-a8 diagonal)
    lambda x, y: (7 - y, x),      # 6 rotate
    lambda x, y: (y, 7 - x),      # 7 rotate the other way
]


def bit(c):
    return 63 - (8 * c[1] + c[0])


def sym_inverse(s):
    probe = [(x, y) for y in range(8) for x in range(8)]
    for t in range(8):
        if all(SYMMETRIES[t](*SYMMETRIES[s](x, y)) == (x, y) for x, y in probe):
            return t
    raise AssertionError(s)


def build():
    patterns = []
    instances = []
    offset = 0
    for pid, (name, cs) in enumerate(BASE_PATTERNS):
        assert len(set(cs)) == len(cs) <= 9, name
        base = sorted(cs, key=bit)
        mask = sum(1 << bit(c) for c in base)
        patterns.append({"name": name, "cells": base, "mask": mask, "size": len(base), "offset": offset})
        seen = set()
        for s, f in enumerate(SYMMETRIES):
            img = [f(*c) for c in base]
            key = frozenset(img)
            if key in seen:
                continue
            seen.add(key)
            instances.append({"pattern": pid, "sym": s, "inv": sym_inverse(s), "cells": img})
        offset += 3 ** len(base)
    return patterns, instances, offset


PATTERNS, INSTANCES, N_ROWS = build()


def fold_rows():
    """Row -> canonical row under each pattern's own symmetries (e.g. a row read a1..h1 or h1..a1).

    Training on canonical rows only and copying them back at export makes the evaluation exactly
    symmetric under the 8 board symmetries, at no cost in the engine.
    """
    fold = list(range(N_ROWS))
    for p in PATTERNS:
        cs = p["cells"]
        n = len(cs)
        perms = []
        for f in SYMMETRIES:
            img = [f(*c) for c in cs]
            if set(img) == set(cs):
                perms.append([cs.index(c) for c in img])  # digit k moves to position perm[k]
        for local in range(3 ** n):
            digits = [(local // 3 ** k) % 3 for k in range(n)]
            best = local
            for perm in perms:
                v = sum(digits[k] * 3 ** perm[k] for k in range(n))
                best = min(best, v)
            fold[p["offset"] + local] = p["offset"] + best
    return fold


def write_header(path):
    lines = [
        "/*",
        "    Egaroucid Project",
        "",
        "    @file nnue_patterns.hpp",
        "        NNUE pattern set (generated by src/tools/nnue/nnue_patterns.py, do not edit)",
        "    @date 2026",
        "    @author Takuto Yamana",
        "    @license GPL-3.0-or-later",
        "*/",
        "",
        "#pragma once",
        "#include <cstdint>",
        "",
        f"constexpr int NNUE_N_PATTERNS = {len(PATTERNS)};",
        f"constexpr int NNUE_N_INSTANCES = {len(INSTANCES)};",
        f"constexpr int NNUE_N_ROWS = {N_ROWS};",
        "",
        "struct Nnue_pattern { uint64_t mask; int size; int offset; };",
        "constexpr Nnue_pattern nnue_patterns[NNUE_N_PATTERNS] = {",
    ]
    for p in PATTERNS:
        lines.append(f"    {{0x{p['mask']:016X}ULL, {p['size']}, {p['offset']}}}, // {p['name']}")
    lines += ["};", "",
              "// pattern id and the symmetry that maps the board onto the base pattern (s^-1)",
              "struct Nnue_instance { int pattern; int inv_sym; };",
              "constexpr Nnue_instance nnue_instances[NNUE_N_INSTANCES] = {"]
    for i in INSTANCES:
        names = " ".join("abcdefgh"[x] + str(y + 1) for x, y in i["cells"])
        lines.append(f"    {{{i['pattern']}, {i['inv']}}}, // {names}")
    lines += ["};", ""]
    Path(path).write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--header", default=str(ROOT / "src/engine/nnue/nnue_patterns.hpp"))
    args = ap.parse_args()
    Path(args.header).parent.mkdir(parents=True, exist_ok=True)
    write_header(args.header)
    counts = {}
    for i in INSTANCES:
        counts[PATTERNS[i["pattern"]]["name"]] = counts.get(PATTERNS[i["pattern"]]["name"], 0) + 1
    print(f"patterns {len(PATTERNS)}, instances {len(INSTANCES)}, rows {N_ROWS}")
    for p in PATTERNS:
        print(f"  {p['name']:14s} size {p['size']} instances {counts[p['name']]}")


if __name__ == "__main__":
    main()
