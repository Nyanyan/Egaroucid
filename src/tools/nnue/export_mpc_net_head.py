"""Write src/engine/nnue/nnue_mpc_net_head.hpp from a trained MPC error model (train_mpc_error.py head.json)
and a z table (calibrate_mpc_net.py output; without it the nominal z of each MPC level is used).

Usage: python src/tools/nnue/export_mpc_net_head.py ignored/nnue_runs/mpcerr_b1/head.json [--z ignored/nnue_runs/mpcerr_b1/z.json]
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
Z_MID = [1.13, 1.55, 1.81, 2.088, 2.1845, 2.7965, 9.99]
Z_END = [1.13, 1.55, 1.81, 2.32, 2.57, 3.29, 9.99]


def arr(a):
    return "{" + ", ".join(repr(float(x)) for x in a) + "}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("head")
    ap.add_argument("--z", default="")
    ap.add_argument("--out", default=str(ROOT / "src" / "engine" / "nnue" / "nnue_mpc_net_head.hpp"))
    args = ap.parse_args()
    h = json.loads(Path(args.head).read_text(encoding="utf-8"))
    if args.z:
        z = json.loads(Path(args.z).read_text(encoding="utf-8"))
        Z, Z_SC = z["Z"], z["Z_END_STATIC_CUT"]
    else:
        Z = [Z_MID, Z_MID, Z_END, Z_END]
        Z_SC = [3.0] * 7
    lines = [
        "// generated by src/tools/nnue/export_mpc_net_head.py from " + Path(args.head).as_posix().split("ignored/")[-1],
        "#pragma once",
        "namespace nnue_mpc_net {",
        "// groups: mid static, mid shallow, end static, end shallow",
        "// mu = MU . [1, D mod 2, (discs - 28) / 14, u, v / 32]",
        "// log sigma = LOG_SIGMA . [1, (discs - 28) / 14, min(s, S_MAX) / 13, min(D - s, GAP_MAX) / 13, u, u^2, |v| / 32]",
        "constexpr double MU[4][5] = {" + ", ".join(arr(r) for r in h["mu"]) + "};",
        "constexpr double LOG_SIGMA[4][7] = {" + ", ".join(arr(r) for r in h["log_sigma"]) + "};",
        "constexpr double S_MAX[4] = " + arr(h["s_max"]) + ";",
        "constexpr double GAP_MAX[4] = " + arr(h["gap_max"]) + ";",
        "// z per group and MPC level (74, 88, 93, 98, 99, 99.9, 100)",
        "constexpr double Z[4][7] = {" + ", ".join(arr(r) for r in Z) + "};",
        "// endgame static cut (the recalibrated path at <= 93%): its own conservative z",
        "constexpr double Z_END_STATIC_CUT[7] = " + arr(Z_SC) + ";",
        "}",
        "",
    ]
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print("wrote", args.out)


if __name__ == "__main__":
    main()
